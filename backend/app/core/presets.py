def generate_builtin_filters(size: int = 33) -> list[str]:
    """Create luts/*.cube and presets/*.json for the 25 built-in filters."""
    LUTS_DIR.mkdir(exist_ok=True)
    PRESETS_DIR.mkdir(exist_ok=True)
    ids = []
    for i, f in enumerate(FILTERS):
        pid = _slug(f["name"])
        Lut3D.from_function(f["lut"], size, f["name"]).write_cube(LUTS_DIR / f"{pid}.cube")
        settings = dict(f.get("settings", {}))
        settings["lut"] = {"name": pid, "strength": float(settings.get("lut", {}).get("strength", 1.0))}
        rec = {"id": pid, "name": f["name"], "group": f["group"], "description": f["desc"], "order": i, "settings": settings}
        (PRESETS_DIR / f"{pid}.json").write_text(json.dumps(rec, indent=1))
        ids.append(pid)
    return ids


