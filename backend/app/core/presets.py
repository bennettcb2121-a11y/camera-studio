GROUPS = ["Film", "Travel", "Portrait", "Sport", "Utility", "User"]


def _slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def preset_record(path: Path) -> dict | None:
    try:
        d = json.loads(path.read_text())
    except Exception:
        return None
    d.setdefault("id", path.stem)
    d.setdefault("group", "User")
    d.setdefault("settings", {})
    d["user"] = path.parent == USER_PRESETS_DIR
    return d


def list_presets() -> list[dict]:
    out = []
    for folder in (PRESETS_DIR, USER_PRESETS_DIR):
        for p in sorted(folder.glob("*.json")):
            r = preset_record(p)
            if r:
                out.append(r)
    order = {g: i for i, g in enumerate(GROUPS)}
    out.sort(key=lambda r: (order.get(r["group"], 99), r.get("order", 999), r["name"]))
    return out


def get_preset(pid: str) -> dict | None:
    for folder in (USER_PRESETS_DIR, PRESETS_DIR):
        p = folder / f"{pid}.json"
        if p.exists():
            return preset_record(p)
    return None


def apply_preset(base: EditSettings, pid: str, strength: float | None = None) -> EditSettings:
    """Preset settings replace the corresponding sliders (crop is left alone)."""
    rec = get_preset(pid)
    if not rec:
        raise KeyError(pid)
    partial = dict(rec["settings"])
    partial.pop("crop", None)
    if strength is not None and "lut" in partial:
        partial["lut"] = {**partial["lut"], "strength": float(strength)}
    return base.merged(partial)


def save_user_preset(name: str, settings: EditSettings | dict, notes: str = "", sources: list[str] | None = None,
                     group: str = "User") -> dict:
    pid = _slug(name) or f"preset-{int(time.time())}"
    s = settings.model_dump() if isinstance(settings, EditSettings) else dict(settings)
    s.pop("crop", None)
    rec = {"id": pid, "name": name, "group": group, "description": notes, "sources": sources or [],
           "settings": s, "created": time.time()}
    (USER_PRESETS_DIR / f"{pid}.json").write_text(json.dumps(rec, indent=1))
    return preset_record(USER_PRESETS_DIR / f"{pid}.json")


def delete_user_preset(pid: str) -> bool:
    p = USER_PRESETS_DIR / f"{pid}.json"
    if p.exists():
        p.unlink()
        return True
    return False


# --------------------------------------------------------------------------- LUT recipes
def _lum(rgb):
    return rgb @ np.array([0.2126, 0.7152, 0.0722], np.float32)


def _sat(rgb, k):
    l = _lum(rgb)[:, None]
    return l + (rgb - l) * k


def _lgg(rgb, lift=(0, 0, 0), gamma=(1, 1, 1), gain=(1, 1, 1)):
    lift, gamma, gain = (np.array(v, np.float32) for v in (lift, gamma, gain))
    out = np.clip(rgb * gain + lift * (1 - rgb), 0, 1)
    return np.power(out, 1.0 / gamma)


def _split_tone(rgb, shadow=(0, 0, 0), highlight=(0, 0, 0), balance=0.0, amount=0.15):
    l = _lum(rgb)[:, None]
    w_hi = np.clip((l - 0.5 + balance) * 2, 0, 1)
    w_sh = 1 - w_hi
    return np.clip(rgb + amount * (w_sh * np.array(shadow, np.float32) + w_hi * np.array(highlight, np.float32)), 0, 1)


def _contrast(rgb, k, mid=0.5):
    return np.clip(mid + (rgb - mid) * k, 0, 1)


def _fade(rgb, amount=0.08):
    return rgb * (1 - amount) + amount


def _bw(rgb, mix=(0.3, 0.59, 0.11)):
    m = np.array(mix, np.float32)
    m = m / m.sum()
    l = (rgb @ m)[:, None]
    return np.repeat(np.clip(l, 0, 1), 3, axis=1)



def _warm(rgb, k=0.05):
    return np.clip(rgb * np.array([1 + k, 1, 1 - k], np.float32), 0, 1)


def _hue_rotate_shadows_highlights(rgb, sh=(0.0, 0.1, 0.12), hi=(0.12, 0.05, -0.05), amount=1.0):
    return _split_tone(rgb, sh, hi, amount=amount)


